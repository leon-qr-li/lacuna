import { chromium } from "@playwright/test";
const theme = process.argv[2] || "dark";
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1440, height: 1000 }, colorScheme: theme });
p.on("console", (m) => m.type() === "error" && !m.text().includes("401") && console.log("console:", m.text()));
await p.addInitScript((th) => { try { localStorage.setItem("lacuna.theme", th); } catch {} }, theme);
await p.goto("http://127.0.0.1:8798/#/ep/EP_AI_%E5%90%88%E6%88%90/listen"); await p.waitForTimeout(2500);
await p.screenshot({ path: `/tmp/claude-0/shots/t_${theme}_1.png`, fullPage: true });
const ws = p.getByTestId("ml-tx").locator(".ml-w");
const a = await ws.nth(8).boundingBox(), c = await ws.nth(13).boundingBox();
await p.mouse.move(a.x + 3, a.y + 5); await p.mouse.down(); await p.mouse.move(c.x + 3, c.y + 5, { steps: 6 }); await p.mouse.up();
await p.waitForTimeout(300);
await p.screenshot({ path: `/tmp/claude-0/shots/t_${theme}_2.png`, fullPage: true });
console.log("bar:", (await p.getByTestId("ml-bar").innerText()).replace(/\n/g, " | "));
await b.close();
